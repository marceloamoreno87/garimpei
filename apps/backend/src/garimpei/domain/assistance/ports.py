from typing import Protocol
from uuid import UUID

from garimpei.domain.assistance.review import ReviewCommand, ReviewTicket


class AssistanceRepository(Protocol):
    def admit(self, command: ReviewCommand) -> ReviewTicket: ...
    def reconcile(self) -> None: ...


class AssistanceQueries(Protocol):
    def listing(self, identity: UUID) -> dict[str, object]: ...
    def coverage(self) -> dict[str, object]: ...
    def operations(self) -> dict[str, object]: ...
