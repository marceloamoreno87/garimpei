from typing import Protocol

from garimpei.domain.integration.values import (
    ConnectionState,
    FacebookSession,
    Group,
    IntegrationConfiguration,
)


class IntegrationRepository(Protocol):
    def read(self) -> IntegrationConfiguration: ...
    def save_facebook(self, session: FacebookSession) -> None: ...
    def configure_whatsapp(
        self, session: str, account: str, group: Group, enabled: bool
    ) -> None: ...
    def disable_whatsapp(self) -> None: ...


class SessionGateway(Protocol):
    def state(self, session: str) -> ConnectionState: ...
    def connect(self, session: str) -> None: ...
    def groups(self, session: str) -> tuple[Group, ...]: ...
    def qr(self, session: str) -> bytes: ...
